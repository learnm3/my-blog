const greetingTriggers = ["你好", "嗨", "哈喽", "hello", "hi", "hey", "在吗", "你是谁"];

export function isGreeting(input: string): boolean {
  const lower = input.toLowerCase();
  return greetingTriggers.some((t) => lower.includes(t));
}

export function getPetResponse(input: string): string {
  const lower = input.toLowerCase();

  for (const rule of rules) {
    if (rule.keywords.some((kw) => lower.includes(kw))) {
      return rule.responses[Math.floor(Math.random() * rule.responses.length)];
    }
  }

  return fallbacks[Math.floor(Math.random() * fallbacks.length)];
}

