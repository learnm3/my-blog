function getSmartFallback(): string {
  const topicFallbacks = fallbacks[lastTopic as keyof typeof fallbacks];
  if (topicFallbacks && topicFallbacks.length > 0 && Math.random() > 0.4) {
    return topicFallbacks[Math.floor(Math.random() * topicFallbacks.length)];
  }
  return fallbacks.general[Math.floor(Math.random() * fallbacks.general.length)];
}

const greetingTriggers = ["你好", "嗨", "哈喽", "hello", "hi", "hey", "在吗", "你是谁"];

export function isGreeting(input: string): boolean {
  const lower = input.toLowerCase();
  return greetingTriggers.some((t) => lower.includes(t));
}

export function getPetResponse(input: string): string {
  const lower = input.toLowerCase();
  conversationCount++;

  for (let i = 0; i < rules.length; i++) {
    if (rules[i].keywords.some((kw) => lower.includes(kw))) {
      lastTopic = topicMap[i] || "general";
      return rules[i].responses[Math.floor(Math.random() * rules[i].responses.length)];
    }
  }

  // 短消息当作闲聊
  if (input.trim().length <= 3) {
    lastTopic = "general";
    return pickRandom([
      "嗯？你在说什么呢~ 没事，慢慢说，我不着急。",
      "虽然我没听懂，但我有在认真听哦！",
      "诶？就这几个字吗？再多说一点嘛~",
    ]);
  }

  return getSmartFallback();
}

function pickRandom(arr: string[]): string {
  return arr[Math.floor(Math.random() * arr.length)];
}

